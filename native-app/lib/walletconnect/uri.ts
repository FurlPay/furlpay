// ---------------------------------------------------------------------------
// WalletConnect v2 pairing URI parsing.
//
// The URI arrives from the three least trustworthy sources in the app: a QR
// code the camera decoded, a deep link another app fired, and the clipboard.
// So this file assumes hostile input throughout and returns a typed failure
// rather than throwing — a scanner that crashes on a malformed QR is a scanner
// that crashes when someone prints a sticker.
//
// SHAPE (CAIP-25 / WalletConnect v2):
//
//   wc:<topic>@<version>?relay-protocol=<p>&symKey=<hex>[&expiryTimestamp=<s>]
//
// WHY VERSION IS CHECKED EXPLICITLY. v1 URIs (`wc:...@1?bridge=...&key=...`)
// are still generated by old dApps and still scan cleanly. The v1 bridge
// network was shut down in June 2023, so a v1 pairing cannot connect to
// anything — it can only hang. Recognising it lets the UI say "this dApp is
// using a retired version of WalletConnect" instead of spinning until timeout.
//
// THE symKey IS A SECRET. It is the symmetric key that decrypts everything on
// the pairing topic. It must never be logged, never be put in an analytics
// property, and never appear in an error message — which is why
// `ParsedPairingUri` keeps it in its own field and `describePairingUri()`
// exists to produce the loggable version.
// ---------------------------------------------------------------------------

export interface ParsedPairingUri {
  topic: string;
  version: 2;
  relayProtocol: string;
  /** SECRET. Never log, never report, never send anywhere but the relay client. */
  symKey: string;
  /** Absent on URIs from older dApp SDKs; those pairings simply have no deadline. */
  expiryTimestampMs?: number;
  relayData?: string;
}

export type PairingUriError =
  | { code: "not_walletconnect"; message: string }
  | { code: "unsupported_version"; message: string; version: number }
  | { code: "malformed"; message: string }
  | { code: "missing_key"; message: string }
  | { code: "expired"; message: string };

export type PairingUriResult = { ok: true; uri: ParsedPairingUri } | { ok: false; error: PairingUriError };

/** 32 bytes, hex. Anything else cannot be an X25519 symmetric key. */
const SYM_KEY_RE = /^[0-9a-f]{64}$/i;
/** Relay topics are 32-byte hex digests. */
const TOPIC_RE = /^[0-9a-f]{64}$/i;

export function parsePairingUri(raw: string, now: number = Date.now()): PairingUriResult {
  const input = raw.trim();

  if (!input.toLowerCase().startsWith("wc:")) {
    return { ok: false, error: { code: "not_walletconnect", message: "Not a WalletConnect link." } };
  }

  // Deliberately NOT `new URL()`. A wc: URI is not hierarchical — there is no
  // `//` — and URL parses the whole `topic@2` as the pathname on some engines
  // and as the host on others. Hermes and Node disagree, which would make this
  // pass in Jest and fail on device. Manual splitting behaves identically
  // everywhere.
  const body = input.slice(3);
  const queryAt = body.indexOf("?");
  const head = queryAt === -1 ? body : body.slice(0, queryAt);
  const query = queryAt === -1 ? "" : body.slice(queryAt + 1);

  const at = head.lastIndexOf("@");
  if (at <= 0) {
    return { ok: false, error: { code: "malformed", message: "Link is missing its version." } };
  }

  const topic = head.slice(0, at);
  const versionRaw = head.slice(at + 1);
  const version = Number(versionRaw);

  if (!Number.isInteger(version)) {
    return { ok: false, error: { code: "malformed", message: "Link has an unreadable version." } };
  }
  if (version !== 2) {
    return {
      ok: false,
      error: {
        code: "unsupported_version",
        version,
        message:
          version === 1
            ? "This dApp uses WalletConnect v1, which was shut down in 2023. Ask them to upgrade."
            : `WalletConnect v${version} is not supported.`,
      },
    };
  }

  if (!TOPIC_RE.test(topic)) {
    return { ok: false, error: { code: "malformed", message: "Link has an invalid pairing topic." } };
  }

  const params = parseQuery(query);
  const symKey = params.get("symkey") ?? "";
  if (!SYM_KEY_RE.test(symKey)) {
    return { ok: false, error: { code: "missing_key", message: "Link is missing its encryption key." } };
  }

  const relayProtocol = params.get("relay-protocol") || "irn";

  let expiryTimestampMs: number | undefined;
  const expRaw = params.get("expirytimestamp");
  if (expRaw) {
    const seconds = Number(expRaw);
    // Seconds since epoch per the spec. Anything non-finite is treated as
    // absent rather than as "expired": rejecting a valid pairing because a dApp
    // sent a junk timestamp is a worse outcome than pairing without a deadline,
    // and the relay enforces its own expiry regardless.
    if (Number.isFinite(seconds) && seconds > 0) {
      expiryTimestampMs = seconds * 1000;
      if (expiryTimestampMs <= now) {
        return {
          ok: false,
          error: { code: "expired", message: "This connection request has expired. Ask the site for a new QR code." },
        };
      }
    }
  }

  return {
    ok: true,
    uri: {
      topic,
      version: 2,
      relayProtocol,
      symKey,
      expiryTimestampMs,
      relayData: params.get("relay-data") ?? undefined,
    },
  };
}

/**
 * Lowercased key/value pairs.
 *
 * Keys are lowercased because `symKey` is camelCase in the spec but arrives
 * lowercased from some QR encoders that normalise the whole payload; matching
 * case-sensitively means those scan and then fail with "missing encryption
 * key", which is a maddening bug to chase from a support ticket.
 */
function parseQuery(query: string): Map<string, string> {
  const out = new Map<string, string>();
  if (!query) return out;
  for (const part of query.split("&")) {
    if (!part) continue;
    const eq = part.indexOf("=");
    const key = eq === -1 ? part : part.slice(0, eq);
    const value = eq === -1 ? "" : part.slice(eq + 1);
    try {
      out.set(decodeURIComponent(key).toLowerCase(), decodeURIComponent(value));
    } catch {
      // A stray `%` makes decodeURIComponent throw. Keep the raw value: a
      // malformed relay-data field must not sink an otherwise valid pairing.
      out.set(key.toLowerCase(), value);
    }
  }
  return out;
}

/**
 * The version of a pairing URI that is safe to log or report.
 *
 * `symKey` is replaced, not truncated. A prefix of a symmetric key is still key
 * material and still narrows a brute force; there is no length at which showing
 * part of it becomes useful enough to justify it.
 */
export function describePairingUri(uri: ParsedPairingUri): Record<string, unknown> {
  return {
    topic: `${uri.topic.slice(0, 8)}…`,
    version: uri.version,
    relayProtocol: uri.relayProtocol,
    hasExpiry: uri.expiryTimestampMs !== undefined,
  };
}

/** True for anything that even claims to be a WalletConnect link. */
export function looksLikePairingUri(raw: string): boolean {
  return raw.trim().toLowerCase().startsWith("wc:");
}
