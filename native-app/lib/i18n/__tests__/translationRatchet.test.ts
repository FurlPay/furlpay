// ---------------------------------------------------------------------------
// Translation ratchet: untranslated strings and missing plural forms.
//
// i18n.test.ts already proves the STRUCTURE (every key present, no extras,
// placeholders preserved, nothing empty) — and locales/types.ts makes a
// missing key a compile error besides. What neither catches:
//
//   1. A value left in English. The old guard was "under 20% identical", which
//      lets a locale ship ~85 English strings and still pass, and never says
//      which ones. A translator cannot act on a percentage.
//   2. A plural set missing a CLDR category the locale uses. plural() falls
//      back to `other`, so French "1 {count} paiements" renders instead of
//      failing — wrong grammar, silently.
//
// Both are now listed KEY BY KEY in translation-baseline.json, and the list may
// only shrink:
//   - a NEW untranslated string or missing plural form fails
//   - a baseline entry that has since been fixed ALSO fails, until it is
//     deleted from the baseline — so the list cannot rot into an exemption
//
// Regenerate the baseline and the human report (docs/i18n/LOCALIZATION_REPORT.md)
// only after a deliberate review:
//
//   I18N_WRITE_BASELINE=1 npx jest lib/i18n/__tests__/translationRatchet.test.ts
//
// Financial, legal and security strings are NOT machine-translated to shrink
// this list. The report exists so a human translator can.
// ---------------------------------------------------------------------------

jest.mock("../../db", () => ({ prefGet: jest.fn(() => null), prefSet: jest.fn() }));

import * as fs from "fs";
import * as path from "path";
import { LOCALES, type Locale } from "../core";
import { en } from "../locales/en";
import { hi } from "../locales/hi";
import { es } from "../locales/es";
import { fr } from "../locales/fr";
import { de } from "../locales/de";
import { pt } from "../locales/pt";
import { ja } from "../locales/ja";
import { ko } from "../locales/ko";
import { zh } from "../locales/zh";

const CATALOGS: Record<Locale, unknown> = { en, hi, es, fr, de, pt, ja, ko, zh };
const TARGETS = LOCALES.filter((l) => l !== "en");
const BASELINE_FILE = path.join(__dirname, "..", "translation-baseline.json");
const REPORT_FILE = path.join(__dirname, "..", "..", "..", "..", "docs", "i18n", "LOCALIZATION_REPORT.md");
const PLURAL_KEYS = new Set(["zero", "one", "two", "few", "many", "other"]);

type Node = Record<string, unknown>;

function isPluralSet(v: unknown): v is Record<string, string> {
  if (typeof v !== "object" || v === null) return false;
  const keys = Object.keys(v);
  return keys.includes("other") && keys.every((k) => PLURAL_KEYS.has(k));
}

/** Dot-paths to every string leaf, and separately to every plural set. */
function walk(obj: unknown, prefix = "", leaves: string[] = [], plurals: string[] = []) {
  if (typeof obj !== "object" || obj === null) return { leaves, plurals };
  if (prefix && isPluralSet(obj)) plurals.push(prefix);
  for (const [k, v] of Object.entries(obj as Node)) {
    const p = prefix ? `${prefix}.${k}` : k;
    if (typeof v === "string") leaves.push(p);
    else walk(v, p, leaves, plurals);
  }
  return { leaves, plurals };
}

function at(obj: unknown, dotted: string): unknown {
  let n: unknown = obj;
  for (const part of dotted.split(".")) {
    if (typeof n !== "object" || n === null) return undefined;
    n = (n as Node)[part];
  }
  return n;
}

const { leaves: EN_LEAVES, plurals: EN_PLURALS } = walk(en);

function untranslated(loc: Locale): string[] {
  return EN_LEAVES.filter((p) => at(CATALOGS[loc], p) === at(en, p)).sort();
}

function missingPluralForms(loc: Locale): string[] {
  const required = new Intl.PluralRules(loc).resolvedOptions().pluralCategories as string[];
  const out: string[] = [];
  for (const p of EN_PLURALS) {
    const set = at(CATALOGS[loc], p) as Record<string, string> | undefined;
    for (const cat of required) if (!set || typeof set[cat] !== "string") out.push(`${p}#${cat}`);
  }
  return out.sort();
}

interface Baseline {
  _doc: string;
  untranslated: Record<string, string[]>;
  missingPluralForms: Record<string, string[]>;
}

function current(): Baseline {
  const u: Record<string, string[]> = {};
  const m: Record<string, string[]> = {};
  for (const loc of TARGETS) {
    u[loc] = untranslated(loc);
    m[loc] = missingPluralForms(loc);
  }
  return {
    _doc:
      "Strings still identical to English, and CLDR plural forms a locale is missing, per locale. " +
      "May only SHRINK. Regenerate with I18N_WRITE_BASELINE=1 after review; see translationRatchet.test.ts.",
    untranslated: u,
    missingPluralForms: m,
  };
}

function report(b: Baseline): string {
  const lines = [
    "# Localization report",
    "",
    "Generated by `native-app/lib/i18n/__tests__/translationRatchet.test.ts` with",
    "`I18N_WRITE_BASELINE=1`. Deterministic: sorted keys, no timestamps.",
    "",
    "Structure (missing keys, extra keys, placeholders, empty values) is enforced separately",
    "by the compiler (`locales/types.ts`) and by `i18n.test.ts`; every locale currently passes those.",
    "This report lists what those checks cannot see.",
    "",
    `English catalog: ${EN_LEAVES.length} strings, ${EN_PLURALS.length} plural sets.`,
    "",
    "| Locale | Identical to English | Missing plural forms |",
    "|---|---|---|",
    ...TARGETS.map((l) => `| ${l} | ${b.untranslated[l].length} | ${b.missingPluralForms[l].length} |`),
    "",
    "Some identical values are legitimate (brand names, tickers, \"OK\"). Each still needs a",
    "translator to confirm it, because the check cannot tell a loanword from a forgotten string.",
    "",
  ];
  for (const l of TARGETS) {
    if (!b.untranslated[l].length && !b.missingPluralForms[l].length) continue;
    lines.push(`## ${l}`, "");
    if (b.untranslated[l].length) {
      lines.push("Identical to English:", "");
      for (const k of b.untranslated[l]) lines.push(`- \`${k}\` — "${String(at(en, k))}"`);
      lines.push("");
    }
    if (b.missingPluralForms[l].length) {
      lines.push("Missing plural forms:", "");
      for (const k of b.missingPluralForms[l]) lines.push(`- \`${k}\``);
      lines.push("");
    }
  }
  return lines.join("\n");
}

const WRITE = process.env.I18N_WRITE_BASELINE === "1";

if (WRITE) {
  it("writes the baseline and the report", () => {
    const b = current();
    fs.writeFileSync(BASELINE_FILE, JSON.stringify(b, null, 2) + "\n");
    fs.mkdirSync(path.dirname(REPORT_FILE), { recursive: true });
    fs.writeFileSync(REPORT_FILE, report(b));
  });
} else {
  const baseline: Baseline = JSON.parse(fs.readFileSync(BASELINE_FILE, "utf8"));
  const now = current();

  describe.each(TARGETS)("%s", (loc) => {
    it("adds no new untranslated string", () => {
      const allowed = new Set(baseline.untranslated[loc] ?? []);
      expect(now.untranslated[loc].filter((k) => !allowed.has(k))).toEqual([]);
    });

    it("has no baseline entry that is now translated (delete it from the baseline)", () => {
      const present = new Set(now.untranslated[loc]);
      expect((baseline.untranslated[loc] ?? []).filter((k) => !present.has(k))).toEqual([]);
    });

    it("drops no new plural form", () => {
      const allowed = new Set(baseline.missingPluralForms[loc] ?? []);
      expect(now.missingPluralForms[loc].filter((k) => !allowed.has(k))).toEqual([]);
    });

    it("has no baseline plural entry that is now fixed", () => {
      const present = new Set(now.missingPluralForms[loc]);
      expect((baseline.missingPluralForms[loc] ?? []).filter((k) => !present.has(k))).toEqual([]);
    });
  });
}
