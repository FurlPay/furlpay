const { withAndroidManifest } = require("expo/config-plugins");

// ---------------------------------------------------------------------------
// Android package visibility for UPI apps (<queries>).
//
// THE BUG THIS EXISTS TO KILL. Android 11 (API 30) made other installed apps
// invisible by default. Without a matching <queries> entry,
// Linking.canOpenURL("upi://pay?…") returns FALSE even when GPay, PhonePe and
// Paytm are all installed — so lib/upi.ts openUpiApp() reports "no UPI app
// found" and the user is told to install one they already have. Nothing throws
// and nothing logs; the feature is simply dead on every modern device.
//
// This app targets API 36 (see expo-build-properties in app.json), so the
// restriction always applies. android/ is gitignored and regenerated by
// `expo prebuild`, so like withNetworkSecurityConfig this has to be a plugin
// rather than a hand-edited manifest, or it silently falls out of a build.
//
// SCOPE. Declaring the `upi` scheme reveals only apps that handle UPI payment
// intents — NPCI requires every PSP app to register it — which is the minimum
// needed to answer "can this device pay by UPI?". No <package> entries are
// added: naming individual apps would be a maintenance list that goes stale as
// PSPs come and go, and it is not needed to resolve the intent.
// ---------------------------------------------------------------------------

const UPI_INTENT_QUERY = {
  intent: [
    {
      action: [{ $: { "android:name": "android.intent.action.VIEW" } }],
      data: [{ $: { "android:scheme": "upi" } }],
    },
  ],
};

/** True when a <queries> block already declares the `upi` scheme. */
function declaresUpi(queries) {
  return queries.some((q) =>
    (q.intent ?? []).some((intent) =>
      (intent.data ?? []).some((d) => d?.$?.["android:scheme"] === "upi")
    )
  );
}

function withUpiQueries(config) {
  return withAndroidManifest(config, (cfg) => {
    const manifest = cfg.modResults.manifest;

    // Merge rather than assign: expo-router and other plugins contribute their
    // own <queries>, and overwriting them would break unrelated intent
    // resolution in a way that is equally silent.
    const existing = Array.isArray(manifest.queries) ? manifest.queries : [];
    if (!declaresUpi(existing)) {
      manifest.queries = [...existing, UPI_INTENT_QUERY];
    }
    return cfg;
  });
}

module.exports = withUpiQueries;
