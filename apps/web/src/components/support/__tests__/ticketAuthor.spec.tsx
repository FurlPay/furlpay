/**
 * @vitest-environment jsdom
 */
import { afterEach, describe, it, expect } from "vitest";
import { cleanup, render, within } from "@testing-library/react";
import { TicketMessage, type ThreadMessage } from "../TicketThread";

// ---------------------------------------------------------------------------
// Who a message is FROM.
//
// This has now been wrong twice in the same way, which is why it gets its own
// spec. `MessageAuthor` in lib/support.ts has four values; this component
// branched on two, then three. The unhandled value does not throw — it falls
// through to the customer branch and renders under the customer's own name,
// avatar and badge. Words in the user's mouth, silently.
//
// For `assistant` that is also a compliance failure, not only a UX one: EU AI
// Act Article 50(2) has applied since 2 August 2026 and requires disclosure
// perceivable in the interaction itself.
//
// Each test asserts the ATTRIBUTION, not the styling — a redesign should be
// free to change colour, and must not be free to reattribute a message.
// ---------------------------------------------------------------------------

const base = { id: "msg_1", body: "Your deposit is confirmed.", createdAt: new Date().toISOString() };

// Scoped to this render's own container, and cleaned up after each test.
// Vitest runs with no global setup file here, so testing-library's auto-cleanup
// is NOT active: without this, every render stays in document.body and a
// `screen` query happily matches the PREVIOUS test's badge. That is exactly how
// the first draft of this spec "failed" — it was finding the agent's "Support"
// pill left behind by the test above.
afterEach(cleanup);

function renderAs(author: ThreadMessage["author"]) {
  const { container } = render(<TicketMessage message={{ ...base, author }} customerName="Alex" />);
  return { container, q: within(container) };
}

describe("TicketMessage attribution", () => {
  it("renders a customer message as the customer", () => {
    const { q } = renderAs("user");
    expect(q.getByText("Alex")).toBeTruthy();
    expect(q.getByText("Customer")).toBeTruthy();
  });

  it("renders a human agent as FurlPay Support", () => {
    const { q } = renderAs("agent");
    expect(q.getByText("FurlPay Support")).toBeTruthy();
    expect(q.getByText("Support")).toBeTruthy();
  });

  it("renders a system note as FurlPay, not the customer", () => {
    const { q } = renderAs("system");
    expect(q.getByText("FurlPay")).toBeTruthy();
    expect(q.getByText("System")).toBeTruthy();
    expect(q.queryByText("Alex")).toBeNull();
  });

  it("renders an AI message as the AI — never under the customer's name", () => {
    // The regression. Before the fourth branch existed this rendered "Alex" and
    // the badge "Customer".
    const { q } = renderAs("assistant");
    expect(q.getByText("FurlPay AI Assistant")).toBeTruthy();
    expect(q.queryByText("Alex")).toBeNull();
    expect(q.queryByText("Customer")).toBeNull();
  });

  it("states in words that the AI is not a human", () => {
    // Article 50 is not satisfied by an icon: the disclosure has to be readable,
    // and it has to be in the message, because a panel heading scrolls away.
    const { container, q } = renderAs("assistant");
    expect(q.getByText("AI — not a human")).toBeTruthy();
    expect(container.textContent).toMatch(/Generated by AI/i);
    expect(container.textContent).toMatch(/cannot act on your account/i);
  });

  it("does not give the AI the human agent's badge", () => {
    // The distinction customers actually rely on. If these ever collide, a
    // customer cannot tell a machine's answer from a specialist's.
    const { q } = renderAs("assistant");
    expect(q.queryByText("Support")).toBeNull();
    expect(q.queryByText("FurlPay Support")).toBeNull();
  });

  it("every author value in the union is attributed to someone", () => {
    // Guards the next added value: if a fifth author appears and nobody adds a
    // branch, it silently becomes the customer again.
    const authors: ThreadMessage["author"][] = ["user", "agent", "system", "assistant"];
    const names = authors.map((a) => {
      const { container, unmount } = render(
        <TicketMessage message={{ ...base, author: a }} customerName="Alex" />
      );
      const name = container.querySelector(".font-semibold")?.textContent ?? "";
      unmount();
      return name;
    });
    // Four authors, four distinct display identities.
    expect(new Set(names).size).toBe(4);
  });
});
